def export_all_embedding_data(output_dir: Path | None = None) -> None:
    """Export verified datasets to JSON for web application."""
    target_dir = output_dir or settings.data_dir
    target_dir.mkdir(parents=True, exist_ok=True)

    words = build_embeddings_dataset()
    presets = build_analogy_presets()
    shifts = build_contextual_shifts()

    with open(target_dir / "embeddings.json", "w", encoding="utf-8") as f:
        json.dump([w.model_dump() for w in words], f, indent=2)

    with open(target_dir / "presets.json", "w", encoding="utf-8") as f:
        json.dump([p.model_dump() for p in presets], f, indent=2)

    with open(target_dir / "contextual_examples.json", "w", encoding="utf-8") as f:
        json.dump([s.model_dump() for s in shifts], f, indent=2)

    logger.info("Successfully exported embedding datasets to %s", target_dir)


if __name__ == "__main__":
    export_all_embedding_data()

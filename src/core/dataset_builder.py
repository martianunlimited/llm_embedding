def normalize_vector(v: list[float]) -> list[float]:
    """L2 normalize a list of floats to unit vector."""
    arr = np.array(v, dtype=float)
    norm = np.linalg.norm(arr)
    if norm == 0:
        return v
    return (arr / norm).tolist()


def build_embeddings_dataset() -> list[WordItem]:
    """Generate normalized vectors and compute 2D and 3D PCA coordinates."""
    raw_matrix = []
    for item in RAW_DEFINITIONS:
        norm_v = normalize_vector(item["raw_vec"])
        item["norm_vec"] = norm_v
        raw_matrix.append(norm_v)

    mat = np.array(raw_matrix)

    # Compute PCA 2D and 3D
    pca2 = PCA(n_components=2, random_state=42)
    coords_2d = pca2.fit_transform(mat)

    pca3 = PCA(n_components=3, random_state=42)
    coords_3d = pca3.fit_transform(mat)

    words: list[WordItem] = []
    for idx, item in enumerate(RAW_DEFINITIONS):
        w_item = WordItem(
            word=item["word"],
            category=item["category"],
            cmu_features=item["cmu"],
            dense_vector=[round(x, 4) for x in item["norm_vec"]],
            pca_2d=[round(float(coords_2d[idx, 0]), 3), round(float(coords_2d[idx, 1]), 3)],
            pca_3d=[
                round(float(coords_3d[idx, 0]), 3),
                round(float(coords_3d[idx, 1]), 3),
                round(float(coords_3d[idx, 2]), 3),
            ],
            description=item["desc"],
        )
        words.append(w_item)

    return words


